// ชื่อประเทศที่ใช้เก็บใน chat_customers.country — ต้องสะกดตรงกันทุกที่
//
// ทำไมต้องมีลิสต์กลาง: เดิมแต่ละที่เขียนคนละแบบ (ตัวซิงก์เขียน "ไทย" · detect-chat-origin
// เขียน "ประเทศไทย" · ตัวแปลเขียน "ภาษาอังกฤษ (ยังระบุประเทศไม่ได้)") ในฐานข้อมูลจริง
// จึงมีทั้ง "ประเทศไทย" 768 แถว และ "ไทย" 108 แถว = ประเทศเดียวกันแต่ตัวกรองแยกเป็นสองกลุ่ม
//
// ค่ามาตรฐานใช้ชื่อสั้น (ไทย ไม่ใช่ ประเทศไทย) และค่าที่แปลว่า "ยังไม่รู้" ให้เก็บเป็นค่าว่าง
// ไม่ใช่ข้อความอย่าง "ไม่สามารถระบุประเทศ" ซึ่งกลายเป็นกลุ่มขยะในตัวกรอง
export const COUNTRIES = [
  "ไทย", "ลาว", "กัมพูชา", "เมียนมา", "เวียดนาม",
  "มาเลเซีย", "อินโดนีเซีย", "ฟิลิปปินส์", "สิงคโปร์",
  "ไต้หวัน", "ฮ่องกง", "จีน", "อินเดีย",
  "ออสเตรเลีย", "สหราชอาณาจักร", "สหรัฐอเมริกา",
];

// ค่าที่เจอในฐานข้อมูลแล้วต้องถือว่า "ยังไม่รู้ประเทศ"
const UNKNOWN = [
  "", "-", "ไม่ทราบ", "ไม่พบประเทศ", "ไม่พบข้อมูลประเทศ",
  "ไม่สามารถระบุประเทศ", "ไม่สามารถระบุประเทศได้",
  "ภาษาอังกฤษ (ยังระบุประเทศไม่ได้)",
];

// ปรับค่าที่อ่านมาให้เป็นชื่อมาตรฐาน — null = ยังไม่รู้ประเทศ
export function normalizeCountry(value) {
  const s = String(value ?? "").trim();
  if (!s || UNKNOWN.includes(s)) return null;
  if (s === "ประเทศไทย" || s === "Thailand" || s === "TH") return "ไทย";
  const hit = COUNTRIES.find((c) => c === s);
  return hit || s;      // ชื่อที่ไม่อยู่ในลิสต์ก็เก็บไว้ตามเดิม ดีกว่าทิ้งข้อมูลของจริง
}
