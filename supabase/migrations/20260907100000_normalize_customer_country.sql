-- รวมชื่อประเทศให้เป็นค่ามาตรฐานเดียว (ดู lib/constants/countries.js)
--
-- ในฐานข้อมูลจริงมีทั้ง "ประเทศไทย" 768 แถว และ "ไทย" 108 แถว = ประเทศเดียวกัน
-- แต่ตัวกรองประเทศในกล่องแชทแยกเป็นสองกลุ่ม · และมีค่าที่แปลว่า "ยังไม่รู้" อีก 200+ แถว
-- ("ภาษาอังกฤษ (ยังระบุประเทศไม่ได้)", "ไม่สามารถระบุประเทศ") ซึ่งกลายเป็นกลุ่มขยะในตัวกรอง
--
-- ค่ามาตรฐาน = ชื่อสั้น ("ไทย") · ยังไม่รู้ = null (ให้ตัวตรวจประเทศเขียนทับได้ทีหลัง)
update public.chat_customers
set country = 'ไทย', updated_at = now()
where country in ('ประเทศไทย', 'Thailand', 'TH');

update public.chat_customers
set country = null, updated_at = now()
where country in ('', '-', 'ไม่ทราบ', 'ไม่พบประเทศ', 'ไม่พบข้อมูลประเทศ',
                  'ไม่สามารถระบุประเทศ', 'ไม่สามารถระบุประเทศได้',
                  'ภาษาอังกฤษ (ยังระบุประเทศไม่ได้)');
